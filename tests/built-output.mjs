import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
const root = resolve(process.argv[2] || 'public-root/dist');
const html = p => readFileSync(resolve(root,p,'index.html'),'utf8');
const home = html('.');
assert.match(home, /<title>[\u{F0000}-\u{F1FFF}]+<\/title>/u, 'glyph-only title');
assert.match(home,/id="workspace"/,'tiled workspace');
assert.equal([...home.matchAll(/class="session/g)].length,4,'four server-rendered sessions');
assert.ok(!home.includes('<nav')&&!home.includes('href="/work/"'),'no immediately available page navigation');
assert.ok(!home.includes('Joshua Harper')&&!home.includes('Horizon Code'),'identity remains deeper');
assert.match(home,/Simulated sessions, not live agents/,'fiction status explicit to assistive technology');
assert.ok(!/class="(?:mast|workline|operator|system-foot|global-controls)"/.test(home),'no outer chrome');
assert.ok(!home.includes('id="translate"'),'no visible English translation mode');
assert.match(home,/name="command"/,'native command input');
assert.match(home,/data-command="interrupt"/,'touch command shortcuts');
assert.match(home,/id="pause"/,'scheduler pause control');
assert.match(home,/static fictional workstation/,'useful noJS fallback');
assert.match(home,/href="#operator"/,'keyboard skip targets operator input');
assert.ok([...home].some(c=>c.codePointAt(0)>=0xF0000&&c.codePointAt(0)<=0xF1FFF),'actual Accelerando glyph ID range');
assert.ok(existsSync(resolve(root,'local-glyph/accelerando-8192.ttf')),'required original glyph font included in deploy artifact');
assert.equal(JSON.parse(readFileSync(resolve(root,'local-glyph/vocabulary.json'))).tokens.length,8192,'real tokenizer vocabulary present');
assert.ok(!/Weyland|Yutani|Nostromo|MOTHER/.test(home),'original not copied film branding');
const work=html('work');
console.log('PASS multiplex static output, local glyphs, no navigation, native controls and noJS');
for (const name of ['Horizon Code','Sloperator','FAE PDF']) assert.ok(work.includes(name), `featured evidence: ${name}`);
assert.match(work, /Illustration, not a screenshot/, 'artifact drawings clearly labeled');
assert.match(work, /early alpha/i, 'Sloperator maturity disclosed');
assert.match(work, /GPU generation is roadmap/, 'no unshipped media capabilities');
assert.match(work, /14 October 2026/, 'dated source snapshot, not live status');
assert.match(html('work'), /Historical artifacts/, 'old work kept separately');
for (const id of ['001','002','003','004','005']) assert.ok(existsSync(resolve(root,`work/${id}/index.html`)), 'legacy work preserved');
console.log('PASS inspectable project selection + historical work');
assert.ok(existsSync(resolve(root,'about/index.html')), 'same-origin about exists');
assert.match(html('about'), /ADP/, 'about retains grounded professional context');
assert.match(html('about'), /contract/, 'ADP contract qualifier retained');
assert.match(html('contact'), /Contact Joshua/, 'same-origin personal contact survives assembly');
assert.match(html('contact'), /mailto:joshua@fullyautomated.enterprises/, 'existing email, no invented service');
assert.ok(!html('contact').includes('calendar.google'), 'no invented calendar');
for (const p of ['hire','resume','about/faq','about/no']) assert.ok(!html(p).includes('https://contact.hellointernet.lol'), `${p} uses root contact`);
console.log('PASS grounded about + reliable same-origin contact');
assert.ok(!home.includes('[object JSON]'), 'diagram prints literal JSON label');
for (const id of ['001','002','003','004','005']) assert.match(html(`work/${id}`), /Historical project note/, 'detail pages disclose historical status');
console.log('PASS literal diagram labels + historical detail context');
// Only assembled-tree runs include the independently served utility pages.
for (const p of ['this','ops']) if (existsSync(resolve(root,`${p}/index.html`))) assert.ok(!html(p).includes('https://contact.hellointernet.lol'), `${p} avoids broken contact host`);
